/** Sends a prompt from the new chat with the clock held, then steps it: one capture per listed time after the thread page mounts. */
async function morph(look: Look, name: string, prompt: string, image?: string, extra: Record<string, string> = {}) {
  const f = await launch(look, { ...(image ? { KYBERN_GPUIX_ATTACH: image } : {}), ...extra })
  try {
    if (image) await until(async () => (await f.app.getByTestId('attachment-image1').count()) > 0, 'image attached', 20000)
    await f.app.getByTestId('composer').fill(prompt)
    await Bun.sleep(400)
    await shot(f, `${name}-before`)
    await f.app.clock.pause()
    await f.app.getByTestId('composer').press('enter')
    // The page switches once the daemon has the thread; then wait (1 ms steps) for the real bubble so the flight leaves.
    await until(async () => { await f.app.clock.fastForward(1); return (await f.app.getByTestId('draft').count()) === 0 }, 'thread page', 20000)
    await until(async () => { await f.app.clock.fastForward(1); return (await f.app.getByTestId('user-bubble').count()) > 0 }, 'first bubble', 20000)
    let at = 0
    for (const ms of [0, 40, 90, 150, 220, 320, 450, 700]) {
      await f.app.clock.fastForward(Math.max(1, ms - at)); at = Math.max(at + 1, ms)
      await f.app.screenshot({ path: `${out}/${name}-${String(ms).padStart(3, '0')}ms.png` })
    }
    await f.app.clock.resume()
  } catch (error) { await f.app.screenshot({ path: `${out}/failed-${name}.png` }).catch(() => {}); console.log(f.diagnostics().slice(-2000)); throw error } finally { await f.close() }
}

