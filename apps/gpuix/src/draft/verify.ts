// ---- frame intervals of one flight on whole-window glass (scene submissions, real time; the card keeps its frost) ----
{
  const f = await launch('glass', { KYBERN_FRAME_TIMES: '1' })
  try {
    await f.app.getByTestId('composer').fill('Make the lightbox zoom follow trackpad pinch on Safari, and keep the image sharp while it scales. Check the grid too.')
    await Bun.sleep(800)
    await f.app.getByTestId('composer').press('enter')
    // From the page switch (polled every few ms) through the 450 ms flight.
    for (let i = 0; i < 2000 && (await f.app.getByTestId('draft').count()) > 0; i++) await Bun.sleep(5)
    const from = f.frameTimes().length
    await Bun.sleep(600)
    const frames = f.frameTimes().slice(from)
    const deltas = frames.slice(1).map((t, i) => t - frames[i]!)
    report.glassFlight = { frames: frames.length, spanMs: Math.round((frames.at(-1) ?? 0) - (frames[0] ?? 0)), p50: percentile(deltas, 0.5), p95: percentile(deltas, 0.95), max: Math.max(...deltas), over16_7: deltas.filter((d) => d > 16.7).length, over33: deltas.filter((d) => d > 33).length }
    await f.app.screenshot({ path: `${out}/morph-glass-landed.png` })
  } finally { await f.close() }
}

