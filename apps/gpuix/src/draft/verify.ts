/** The hero chevron, zoomed: the name's tail and the chevron, 4× (the capture is 2×). */
async function chevronCrop(f: Fixture, name: string) {
  const box = await f.app.getByTestId('draft-hero').bounds()
  const file = `${out}/${name}-full.png`
  await settle(f)
  await f.app.screenshot({ path: file })
  const crop = `${out}/${name}.png`
  const w = 120, h = Math.round(box.height + 8)
  const x = Math.round(box.x + box.width - w), y = Math.round(box.y - 4)
  Bun.spawnSync(['sips', '-c', String(h * 2), String(w * 2), '--cropOffset', String(y * 2), String(x * 2), file, '--out', crop], { stdout: 'ignore' })
  Bun.spawnSync(['sips', '-z', String(h * 4), String(w * 4), crop], { stdout: 'ignore' })
  // The optical check: the chevron's ink centre against the x-height band's centre, and the visible gap.
  const size = Number(name.split('-')[1]), chevron = heroChevron(size as 34 | 28 | 24)
  const band = Bun.spawnSync(['swift', path.join(import.meta.dir, 'chevron-band.swift'), file, String(Math.round(box.x * 2 + 28)), String(Math.round(box.y * 2)), String(Math.round(box.width * 2 - 40)), String(Math.round(box.height * 2)), String(Math.round((box.x + box.width - 10 - chevron.width - 3) * 2))])
  report[name] = { box, band: band.stdout.toString().trim().split('\n') }
}

