import { mkdirSync } from 'node:fs'
import { assertScratchEnv } from '../requests/harness.ts'
import path from 'node:path'
import assert from 'node:assert/strict'
import { launch } from '@gpuix/react/automation'
import { pagesFixture } from '../../scripts/pages-fixture.ts'
import { verifyPrRecovery } from '../../scripts/pages-recovery.ts'
const out = process.env.KYBERN_VERIFY_OUTPUT ?? '/Users/mymac/projects/ade/previews/gpuix/pages'
mkdirSync(out, { recursive: true })
const fixture = pagesFixture()
const variant = process.argv.includes('--light') ? 'light' : 'dark'
const reduced = process.argv.includes('--reduced')
const watchdog = setTimeout(() => process.exit(1), 240_000)
assertScratchEnv({ ...fixture.env })
const app = await launch({ command: 'bun', args: [path.join(import.meta.dir, '../main.tsx')], env: { ...process.env, ...fixture.env, KYBERN_APPEARANCE: variant, KYBERN_REDUCED_MOTION: reduced ? '1' : '0' } })
const sleep = (ms: number) => new Promise(r => setTimeout(r, ms))
const click = async (id: string) => { console.log('Click', id); await app.getByTestId(id).waitFor({ timeoutMs: 10000 }); await app.getByTestId(id).click() }
const screenshot = async (name: string) => { await app.mouse.move({ x: 1200, y: 40 }); await sleep(300); await app.screenshot({ path: `${out}/fixture-${name}-${variant}${reduced ? '-reduced' : ''}.png` }) }
try {
  await app.getByTestId('app-ready').waitFor({ timeoutMs: 20000 })
  await sleep(500)
  await click('rail-usage')
  await app.getByTestId('usage-stats').waitFor({ timeoutMs: 10000 })
  await screenshot('usage')
  await app.mouse.wheel({ x: 1100, y: 600 }, 0, -600)
  await sleep(400)
  await screenshot('usage-breakdown')
  await app.mouse.wheel({ x: 1100, y: 600 }, 0, 1200)
  await sleep(400)
  await app.getByTestId('usage-group-model').press('enter')
  await sleep(200)
  assert.match(await app.getByTestId('page-usage').textContent(), /claude-opus-5-5/)
  await click('usage-period')
  await click('usage-period-7')
  await app.getByTestId('usage-stats').waitFor({timeoutMs:10000})
  await app.mouse.wheel({x:1100,y:600},0,-300)
  await app.getByTestId('usage-chart').waitFor({timeoutMs:10000})
  assert.equal((await app.getByType('div').all()).filter(n => n.testId?.startsWith('usage-bar-')).length, 7)
  await click('rail-pulls')
  await app.getByTestId('pr-row-108').waitFor({ timeoutMs: 10000 })
  await app.getByTestId('pr-search').fill('108')
  await sleep(250)
  assert.equal((await app.getByType('div').all()).filter(n => n.testId?.startsWith('pr-row-')).length, 1)
  await click('pr-row-108')
  await app.getByTestId('pr-summary').waitFor({ timeoutMs: 10000 })
  await screenshot('summary')
  await click('pr-tab-changes')
  await app.getByTestId('pr-native-diff').waitFor({ timeoutMs: 10000 })
  await sleep(200)
  await screenshot('large-diff')
  const diff = await app.getByTestId('pr-native-diff').bounds()
  await app.mouse.click({ x: diff.x + 80, y: diff.y + 73 })
  await app.getByTestId('pr-inline-body').waitFor({ timeoutMs: 3000 })
  await app.getByTestId('pr-inline-body').fill('Preserve this row identity while streaming.')
  await click('pr-inline-save')
  await click('pr-review')
  await app.getByTestId('pr-review-body').fill('Checked the native diff and stable rows.')
  await screenshot('review-draft')
  await app.getByTestId('pr-review-popover').press('escape')
  await click('rail-home')
  await click('rail-pulls')
  await app.getByTestId('pr-summary').waitFor({ timeoutMs: 10000 })
  await click('pr-review')
  assert.match(await app.getByTestId('pr-review-popover').textContent(), /1 inline comment/)
  await app.getByTestId('pr-review-popover').press('escape')
  await click('pr-tab-timeline')
  await sleep(300)
  await screenshot('timeline')
  await click('pr-timeline-filter-reviews')
  await sleep(700)
  // The next cursor page loads from the end of the history.
  await app.getByTestId('pr-timeline-more').press('enter')
  await sleep(700)
  assert.match(await app.getByTestId('pr-timeline').textContent(), /approved these changes/)
  await click('pr-send')
  await screenshot('send')
  await app.getByTestId('pr-send-popover').press('escape')
  await click('pr-merge')
  assert.match(await app.getByTestId('pr-confirm').textContent(), /Squash merge #108/)
  await screenshot('merge-confirm')
  await app.getByTestId('pr-confirm').press('escape')
  await app.getByTestId('pr-search').press('cmd-b')
  await screenshot('sidebar-peek')
  await app.getByTestId('pr-search').press('cmd-b')
  await sleep(700)
  await verifyPrRecovery(app, fixture, 'missing')
  await screenshot('gh-missing')
  await verifyPrRecovery(app, fixture, 'auth')
  await screenshot('gh-auth')
  assert.ok(!fixture.calls.some(m => ['github.pr.action', 'threads.send', 'threads.create'].includes(m)), 'Verification must never submit a write action')
  console.log('PASS: usage grouping/period, PR search, native 2400-line diff, inline draft, remount retention, timeline paging, send/merge UI, sidebar peek, GitHub recovery states; no write RPCs')
} finally { clearTimeout(watchdog); await app.close(); fixture.close() }
