/**
 * Regenerates `xterm.json`: what xterm.js 6.0.0 (the desktop terminal, in WebKit)
 * holds after each case in `cases.ts`. Needs the desktop's xterm package:
 *
 *   XTERM_JS=/path/to/@xterm/xterm/lib/xterm.js bun src/terminal/reference/dump-xterm.ts
 *
 * The JSON is committed so `bun test ./src` needs neither WebKit nor xterm.
 */
import { writeFileSync } from 'node:fs'
import { CASES } from './cases.ts'

const PLAYWRIGHT = process.env.PLAYWRIGHT_CORE ?? '/Users/mymac/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright-core/index.mjs'
const XTERM = process.env.XTERM_JS ?? '/Users/mymac/projects/ade/apps/desktop/node_modules/@xterm/xterm/lib/xterm.js'
const { webkit } = await import(PLAYWRIGHT)
const browser = await webkit.launch()
const page = await browser.newPage()
await page.setContent('<div id="t"></div>')
await page.addScriptTag({ path: XTERM })
const result = await page.evaluate(async (cases: typeof CASES) => {
  const out: Record<string, unknown> = {}
  const dumpBuffer = (term: any, buf: any) => {
    const rows: unknown[] = []
    for (let y = 0; y < buf.length; y++) {
      const line = buf.getLine(y)!, cells: string[] = []
      for (let x = 0; x < term.cols; x++) {
        const c = line.getCell(x)!
        const flags = [c.isBold() && 'b', c.isItalic() && 'i', c.isUnderline() && 'u', c.isInverse() && 'v', c.isDim() && 'd', c.isStrikethrough() && 's', c.isInvisible() && 'h', c.isBlink() && 'k', c.isOverline() && 'o'].filter(Boolean).join('')
        const color = (mode: number, value: number) => mode === 0 ? '-' : mode === 50331648 ? `#${value.toString(16).padStart(6, '0')}` : String(value)
        cells.push(`${c.getWidth() === 0 ? '' : c.getChars() || ' '}|${color(c.getFgColorMode(), c.getFgColor())}|${color(c.getBgColorMode(), c.getBgColor())}|${flags}`)
      }
      rows.push({ wrapped: line.isWrapped, cells })
    }
    return rows
  }
  for (const c of cases) {
    document.getElementById('t')!.innerHTML = ''
    const term = new (window as any).Terminal({ cols: c.cols, rows: c.rows, allowProposedApi: true, scrollback: 100 })
    term.open(document.getElementById('t')!)
    const replies: string[] = []
    term.onData((d: string) => replies.push(d))
    let title = ''
    term.onTitleChange((t: string) => { title = t })
    for (const step of c.steps) {
      if (typeof step === 'string') await new Promise<void>(r => term.write(step, r))
      else term.resize(step.resize[0], step.resize[1])
    }
    const active = term.buffer.active
    out[c.name] = {
      alt: active.type === 'alternate', cursorX: active.cursorX, cursorY: active.cursorY, baseY: active.baseY, title, replies,
      modes: { bracketedPaste: term.modes.bracketedPasteMode, applicationCursor: term.modes.applicationCursorKeysMode, mouse: term.modes.mouseTrackingMode, wrap: term.modes.wraparoundMode, insert: term.modes.insertMode, origin: term.modes.originMode },
      rows: dumpBuffer(term, active),
    }
    term.dispose()
  }
  return out
}, CASES)
const widths = await page.evaluate(() => {
  const term = new (window as any).Terminal({ cols: 20, rows: 5, allowProposedApi: true })
  term.open(document.getElementById('t')!)
  const unicode = term._core.unicodeService, zero: number[][] = [], two: number[][] = []
  let z: number[] | null = null, t: number[] | null = null
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue
    const w = unicode.wcwidth(cp)
    if (w === 0) { if (z && z[1] === cp - 1) z[1] = cp; else { z = [cp, cp]; zero.push(z) } }
    if (w === 2) { if (t && t[1] === cp - 1) t[1] = cp; else { t = [cp, cp]; two.push(t) } }
  }
  return { zero, two }
})
await browser.close()
const flat = (ranges: number[][]) => ranges.flat().map(n => '0x' + n.toString(16)).join(', ')
writeFileSync(new URL('../width.ts', import.meta.url), `// Generated by reference/dump-xterm.ts from xterm.js 6.0.0's default (Unicode 6) width table.
// Flat [first, last, first, last, ...] code point ranges that occupy zero or two cells; everything else takes one.
export const ZERO_WIDTH = [${flat(widths.zero)}]
export const DOUBLE_WIDTH = [${flat(widths.two)}]
`)
writeFileSync(new URL('./xterm.json', import.meta.url), JSON.stringify(result, null, 1))
console.log(`wrote ${Object.keys(result).length} cases`)
