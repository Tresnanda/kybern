// Frame strips (20/50/80 % of each motion) for the zoom and panel items, in one theme.
import { open, thread, scrub, OUT } from "./probe-lib.mjs"
const scheme = process.env.SCHEME || "dark"
const tag = `scrub-${scheme}`
const { browser, page } = await open({ scheme })
await thread(page, "Explain the retry")
await page.waitForTimeout(1200)
const expand = page.getByLabel("Expand preview").first()
await expand.scrollIntoViewIfNeeded()
const box = await expand.boundingBox()
await page.mouse.move(box.x - 40, box.y + 40)
await page.waitForTimeout(400)
await scrub(page, `${tag}-visual-expand`, () => page.mouse.click(box.x + box.width / 2, box.y + box.height / 2))
await scrub(page, `${tag}-visual-collapse`, () => page.getByLabel("Close expanded preview").click())
await thread(page, "Fix the retry loop")
await page.locator('input[type="file"]').first().setInputFiles(new URL("./lightbox-fixture.png", import.meta.url).pathname)
await page.waitForTimeout(800)
await page.locator('[data-testid="composer-editor"]').click()
await page.keyboard.type("image please")
await page.keyboard.press("Enter")
await page.waitForTimeout(2500)
const thumb = page.getByLabel(/Preview Attached image/).last()
await thumb.scrollIntoViewIfNeeded()
await scrub(page, `${tag}-lightbox-open`, () => thumb.click())
await page.waitForTimeout(500)
await scrub(page, `${tag}-lightbox-close`, () => page.getByLabel("Close").first().click())
await browser.close()
