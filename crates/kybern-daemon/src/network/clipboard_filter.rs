    fn private_key_blocks_are_secrets() {
        for kind in
            ["RSA PRIVATE KEY", "OPENSSH PRIVATE KEY", "PRIVATE KEY", "EC PRIVATE KEY", "ENCRYPTED PRIVATE KEY", "PGP PRIVATE KEY BLOCK"]
        {
            let block = format!("-----BEGIN {kind}-----\nMIIEvQIBADANBgkqhkiG9w0BAQEFAASC\n-----END {kind}-----\n");
            assert_eq!(secret(&block), Some(SecretReason::PrivateKey), "{kind}");
            assert_eq!(secret(&format!("my key:\n\n  {block}")), Some(SecretReason::PrivateKey), "indented in text: {kind}");
        }
        // Public material and certificates are meant to be shared.
        assert_eq!(secret("-----BEGIN PUBLIC KEY-----\nMFkwEwYHKoZIzj0CAQYIKoZIzj0DAQcDQgAE\n-----END PUBLIC KEY-----"), None);
        assert_eq!(
            secret("-----BEGIN CERTIFICATE-----\nMIIDdzCCAl+gAwIBAgIEAgAAuTANBgkqhkiG9w0BAQUFADBa\n-----END CERTIFICATE-----"),
            None
        );
        assert_eq!(secret("a private key is a secret number"), None);
    }

