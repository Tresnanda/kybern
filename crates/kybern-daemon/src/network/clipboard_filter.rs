    #[test]
    fn skips_are_counted_by_reason_and_carry_no_text() {
        let counter = SkipCounter::default();
        let key = fake(&["s", "k-"], BODY, 40);
        for text in [key.as_str(), key.as_str(), "plain words", "OPENAI_API_KEY=Zq8mT3vN7xB2cL5wR9"] {
            counter.record(classify(text, Markers::default()));
        }
        counter.record(classify("anything", Markers { concealed: true, transient: false }));
        assert_eq!(counter.count(SecretReason::TokenShape), 2);
        assert_eq!(counter.count(SecretReason::EnvLine), 1);
        assert_eq!(counter.count(SecretReason::Concealed), 1);
        assert_eq!(counter.count(SecretReason::Jwt), 0);
        assert_eq!(counter.total(), 4);
        let rendered = format!("{counter:?} {:?}", classify(&key, Markers::default()));
        assert!(!rendered.contains(&key), "neither the counter nor a verdict can print the text");
        assert!(SecretReason::ALL.iter().all(|r| !r.as_str().is_empty()));
        assert!(Verdict::Shareable.is_shareable());
    }

