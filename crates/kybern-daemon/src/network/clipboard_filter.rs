    #[test]
    fn one_long_high_entropy_token_is_a_secret() {
        // Mixed case and digits, 24+ characters, more than 4.0 bits per character.
        let random = "q7Zk3Vx9Lp2Rt5Ym8Wn1Bc4Dg6Hj0Fs";
        assert!(shannon_entropy(random) > 4.0);
        assert_eq!(secret(random), Some(SecretReason::HighEntropyToken));
        assert_eq!(secret(&format!("  {random}\n")), Some(SecretReason::HighEntropyToken), "surrounding whitespace is ignored");
        assert_eq!(secret("Kj8#mP2$vL9@xQ4!nR7&wT5*"), Some(SecretReason::HighEntropyToken));
        // Letters only needs a higher bar than an identifier reaches.
        assert_eq!(secret("qWzXkLpRtYmNbVcDfGhJsAeUoI"), Some(SecretReason::HighEntropyToken));
        // The same string inside a sentence is not "a single token".
        assert_eq!(secret(&format!("the id is {random} okay")), None);
        // Under 20 characters, or low entropy.
        assert_eq!(secret("q7Zk3Vx9Lp2Rt5Ym8"), None);
        assert_eq!(secret("aaaaaaaaaaaaaaaaaaaaaaaaaaaa"), None);
        assert_eq!(secret("aAaAaAaAaAaAaAaAaAaAaAaAaA"), None);
    }

